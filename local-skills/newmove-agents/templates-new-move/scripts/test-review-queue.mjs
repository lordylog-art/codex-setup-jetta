assert.equal(remainingSurfaces(surfaces,restoreDraft(configuredManifest,()=>JSON.stringify(automatic))).length,2);
automatic.items[0].configuration={};
assert.equal(remainingSurfaces(surfaces,restoreDraft(configuredManifest,()=>JSON.stringify(automatic))).length,2);
