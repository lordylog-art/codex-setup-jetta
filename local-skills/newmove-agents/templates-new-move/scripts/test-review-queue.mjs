const stored=new Map([['template-review:'+JSON.stringify(previousManifest),JSON.stringify(draft)]]);
const restored=restoreDraft(revised,key=>stored.get(key));
assert.equal(restored.items[1].configuration['principal.tamanho'],'amplo');
assert.equal(restored.items[0].decision,'agree');
assert.deepEqual(restored.approvedItems,draft.approvedItems);
assert.equal(draft.items[1].configuration,undefined);
assert.equal(restoreDraft({...revised,grooming:'outra-tarefa'},key=>stored.get(key)),null);
stored.set('template-review:'+JSON.stringify(revised),JSON.stringify({items:[{id:'b',text:'rascunho novo'}]}));
assert.equal(restoreDraft(revised,key=>stored.get(key)).items[0].text,'rascunho novo');
const seed=restoreDraft({grooming:'tarefa-a',deliveredReview:{feedback,delivery:{status:'sent'}}},()=>null);
assert.equal(seed.items[0].decision,'agree');
assert.equal(remainingSurfaces(surfaces,seed).length,2);
assert.equal(restoreDraft({grooming:'tarefa-a',deliveredReview:{feedback,delivery:{status:'failed'}}},()=>null),null);
