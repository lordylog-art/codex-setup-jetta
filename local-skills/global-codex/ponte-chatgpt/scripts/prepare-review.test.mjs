import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

test('published snapshot, exact scope, missing proof and sensitive data are enforced', async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'agentify-review-bundle-'));
  const repo = path.join(dir, 'repo'); const bare = path.join(dir, 'origin.git');
  await fs.mkdir(repo);
  const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git('init'); git('config', 'user.name', 'Review Test'); git('config', 'user.email', 'test@localhost');
  git('init', '--bare', bare);
  git('remote', 'add', 'origin', 'https://github.com/review-test/fixture.git');
  git('config', 'url.' + bare.replaceAll('\\', '/') + '.insteadOf', 'https://github.com/review-test/fixture.git');
  await fs.writeFile(path.join(repo, 'code.mjs'), 'export const value = 1;\n');
  git('add', '--', 'code.mjs'); git('-c', 'maintenance.auto=false', 'commit', '-m', 'base');
  const base = git('rev-parse', 'HEAD');
  await fs.writeFile(path.join(repo, 'code.mjs'), 'export const value = 2;\n');
  await fs.writeFile(path.join(repo, 'unrelated.txt'), 'do not export\n');
  git('add', '--', 'code.mjs', 'unrelated.txt'); git('-c', 'maintenance.auto=false', 'commit', '-m', 'candidate');
  const head = git('rev-parse', 'HEAD'); git('push', 'origin', 'HEAD:refs/heads/review');
  const helper = fileURLToPath(new URL('./prepare-review.mjs', import.meta.url));
  const run = (file, sha = head, output = path.join(dir, 'bundle-' + Math.random() + '.txt')) => {
    const result = spawnSync(process.execPath, [helper, '--repo', repo, '--base', base, '--head', sha, '--branch', 'review', '--output', output, '--file', file], { encoding: 'utf8' });
    return { ...result, output };
  };
  const good = run('code.mjs'); assert.equal(good.status, 0, good.stderr);
  const bundle = JSON.parse(await fs.readFile(good.output, 'utf8'));
  assert.deepEqual(bundle.scope, ['code.mjs']); assert.equal(bundle.snapshots.length, 1);
  assert.equal(bundle.publicationProof, 'exact-tip'); assert.equal(bundle.base, base); assert.equal(bundle.head, head);
  assert.equal(bundle.snapshots[0].head.content, 'export const value = 2;\n');
  assert(!bundle.patch.includes('unrelated.txt'));
  const originalBundle = await fs.readFile(good.output, 'utf8');
  const overwrite = run('code.mjs', head, good.output);
  assert.notEqual(overwrite.status, 0);
  assert.equal(await fs.readFile(good.output, 'utf8'), originalBundle);
  assert.match(run('code.mjs', head.slice(0, 8)).stderr, /full_sha_required/);
  assert.match(run('../outside').stderr, /invalid_path/);
  assert.match(run('/outside').stderr, /invalid_path/);
  assert.match(run('folder\\outside').stderr, /invalid_path/);
  assert.match(run('.env').stderr, /sensitive_path/);
  assert.match(run('keys/private.pem').stderr, /sensitive_path/);
  assert.match(run('absent.mjs').stderr, /selected_file_not_changed/);
  await fs.writeFile(path.join(repo, 'code.mjs'), 'export const value = 3;\n');
  git('add', '--', 'code.mjs'); git('-c', 'maintenance.auto=false', 'commit', '-m', 'unpublished');
  const unpublished = git('rev-parse', 'HEAD');
  assert.match(run('code.mjs', unpublished).stderr, /candidate_not_published_on_branch/);
  await fs.writeFile(path.join(repo, 'code.mjs'), "export const token = 'ghp_" + 'a'.repeat(30) + "';\n");
  git('add', '--', 'code.mjs'); git('-c', 'maintenance.auto=false', 'commit', '-m', 'sensitive');
  const sensitive = git('rev-parse', 'HEAD'); git('push', 'origin', 'HEAD:refs/heads/review');
  const old = run('code.mjs'); assert.equal(old.status, 0, old.stderr);
  assert.equal(JSON.parse(await fs.readFile(old.output, 'utf8')).publicationProof, 'ancestor-of-tip');
  const rejected = run('code.mjs', sensitive); assert.match(rejected.stderr, /possible_secret_in_bundle/);
  await assert.rejects(fs.stat(rejected.output), { code: 'ENOENT' });
  await fs.writeFile(path.join(repo, 'binary.dat'), Buffer.from([0, 1, 2, 3]));
  await fs.writeFile(path.join(repo, 'large.txt'), 'x'.repeat(210000));
  git('add', '--', 'binary.dat', 'large.txt'); git('-c', 'maintenance.auto=false', 'commit', '-m', 'limits');
  const limits = git('rev-parse', 'HEAD'); git('push', 'origin', 'HEAD:refs/heads/review');
  const binary = run('binary.dat', limits); assert.match(binary.stderr, /utf8_text_required/);
  await assert.rejects(fs.stat(binary.output), { code: 'ENOENT' });
  const large = run('large.txt', limits); assert.match(large.stderr, /bundle_too_large/);
  await assert.rejects(fs.stat(large.output), { code: 'ENOENT' });
});
